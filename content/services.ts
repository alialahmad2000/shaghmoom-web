export function getService(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug);
}

export function servicesByCategory(category: ServiceCategory): Service[] {
  return services.filter((s) => s.category === category);
}

/** A few related services (same category, excluding self) for internal links. */
export function relatedServices(slug: string, count = 4): Service[] {
  const self = getService(slug);
  if (!self) return [];
  return services
    .filter((s) => s.category === self.category && s.slug !== slug)
    .slice(0, count);
}
